//! Where `ascribe agents index` writes: the index between markers in a file
//! the product's team keeps, such as its `AGENTS.md`, and each page's
//! Markdown version in the folder the index points into. Neither may be one
//! of the project's pages, and nothing is written when either can't be.

use std::path::{Path, PathBuf};

use ascribe_core::RelPath;
use ascribe_core::path::{normalize, relative_path};
use ascribe_query::AgentsIndex;
use ascribe_resolve::is_source_path;

use super::markers::{Comment, Markers};
use super::sync::{SyncError, read};

/// The index's markers.
pub const MARKERS: Markers<'static> = Markers {
    name: "ascribe:agents:index",
    note: "generated by `ascribe agents index`; run it again rather than editing this block",
    comment: Comment::Html,
};

/// What writing an index changed.
#[derive(Debug, Default)]
pub struct Written {
    /// Whether the file the index is placed in changed.
    pub changed: bool,
    /// How many pages in the folder changed.
    pub pages_changed: usize,
    /// The Markdown files in the folder that aren't the index's pages, such
    /// as the pages of an earlier run that the build no longer offers, from
    /// the folder.
    pub stray: Vec<String>,
}

/// The path from the folder an index is read in, `from`, to the folder its
/// pages are copied into, `folder`, with `/`: the start of each address.
/// Both are absolute and normalized. The folder as written when the two
/// share no root.
pub fn folder_address(from: &Path, folder: &Path) -> String {
    match relative_path(from, folder) {
        Some(rel) if rel.as_str().is_empty() => ".".to_owned(),
        Some(rel) => rel.as_str().to_owned(),
        None => folder.display().to_string().replace('\\', "/"),
    }
}

/// Places `index` between its markers in `file`, and writes its pages into
/// `folder`. Both paths are absolute and normalized; `content` is the
/// project's content root, likewise. Every file is checked and read before
/// any is written.
///
/// # Errors
///
/// A file would be one of the project's pages, `file`'s markers are
/// damaged, or a file can't be read or written.
pub fn write(
    index: &AgentsIndex,
    file: Option<&Path>,
    folder: Option<&Path>,
    content: &Path,
) -> Result<Written, SyncError> {
    // Each file: where, its text now, its text after, and whether it's the
    // file the index is placed in.
    let mut planned: Vec<(PathBuf, Option<String>, String, bool)> = Vec::new();
    if let Some(file) = file {
        refuse_in_content(content, file)?;
        let old = read(file)?;
        let new = MARKERS
            .place(old.as_deref(), &index.text)
            .map_err(|damage| SyncError::Damaged {
                path: file.display().to_string(),
                name: MARKERS.name.to_owned(),
                damage,
            })?;
        planned.push((file.to_owned(), old, new, true));
    }
    if let Some(folder) = folder {
        for page in &index.pages {
            let path = normalize(&folder.join(&page.path));
            refuse_in_content(content, &path)?;
            let old = read(&path)?;
            planned.push((path, old, page.text.clone(), false));
        }
    }
    let mut written = Written::default();
    for (path, old, new, is_file) in &planned {
        if old.as_deref() == Some(new.as_str()) {
            continue;
        }
        if *is_file {
            written.changed = true;
        } else {
            written.pages_changed += 1;
        }
        let failed = |source| SyncError::Write {
            path: path.display().to_string(),
            source,
        };
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(failed)?;
        }
        // Outside FileSystem: a file and a folder named on the command line,
        // which aren't the project's pages.
        std::fs::write(path, new).map_err(failed)?;
    }
    if let Some(folder) = folder {
        let ours: Vec<&str> = index.pages.iter().map(|p| p.path.as_str()).collect();
        // The file the index is placed in may be in the folder, as a
        // package's `AGENTS.md` at the root of what it ships is.
        let own = file
            .and_then(|file| relative_path(folder, file))
            .map(|rel| rel.as_str().to_owned());
        let mut found = Vec::new();
        markdown_files(folder, folder, &mut found);
        found.retain(|path| !ours.contains(&path.as_str()) && own.as_ref() != Some(path));
        found.sort();
        written.stray = found;
    }
    Ok(written)
}

/// An error when `path` is under the content root, where it would be one
/// of the project's pages.
fn refuse_in_content(content: &Path, path: &Path) -> Result<(), SyncError> {
    match relative_path(content, path) {
        Some(rel) if is_source_path(&rel) => Err(SyncError::InContent {
            path: path.display().to_string(),
        }),
        _ => Ok(()),
    }
}

/// The Markdown files under `dir`, as paths from `root` with `/`, added to
/// `found`. A folder that can't be read is passed over.
fn markdown_files(root: &Path, dir: &Path, found: &mut Vec<String>) {
    // Outside FileSystem: the folder the pages are copied into, which isn't
    // the project's.
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let Ok(kind) = entry.file_type() else {
            continue;
        };
        if kind.is_dir() {
            markdown_files(root, &path, found);
        } else if path.extension().is_some_and(|e| e == "md")
            && let Some(rel) = relative_path(root, &path)
        {
            found.push(RelPath::as_str(&rel).to_owned());
        }
    }
}
