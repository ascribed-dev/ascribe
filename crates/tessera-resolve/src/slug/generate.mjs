// Regenerates `table.rs` and `fixtures/*.json` from the real `github-slugger`.
//
//   npm install --prefix <tmp> github-slugger@2.0.0
//   NODE_PATH=<tmp>/node_modules node generate.mjs
//
// The Rust port is checked against this package's actual output, so run this
// against the version recorded in `mod.rs` and commit the result.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const req = createRequire(join(process.env.NODE_PATH ?? '.', 'x.js'))
const pkgDir = dirname(req.resolve('github-slugger/package.json'))
const pkg = req('github-slugger/package.json')
const { default: GithubSlugger, slug } = await import(
  pathToFileURL(join(pkgDir, 'index.js')).href
)
const { regex } = await import(pathToFileURL(join(pkgDir, 'regex.js')).href)

// Removed scalar values, as ranges. The upstream regex is written over UTF-16
// code units with explicit surrogate-pair alternatives, so testing one whole
// scalar at a time is exact. (Lone surrogates can't occur in a Rust `str`.)
const removed = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  regex.lastIndex = 0
  const s = String.fromCodePoint(cp)
  const gone = s.replace(regex, '') === ''
  if (gone) {
    const last = removed[removed.length - 1]
    if (last && last[1] === cp - 1) last[1] = cp
    else removed.push([cp, cp])
  }
}
const hex = (n) => '0x' + n.toString(16).toUpperCase().padStart(4, '0')
let rs = `// @generated by generate.mjs from github-slugger ${pkg.version}. Do not edit.\n\n`
rs += `/// The scalar values \`github-slugger\` ${pkg.version} removes after lowercasing, as\n`
rs += `/// inclusive \`(first, last)\` ranges in ascending order.\n`
rs += `pub(super) const REMOVED: &[(u32, u32)] = &[\n`
for (const [a, b] of removed) rs += `    (${hex(a)}, ${hex(b)}),\n`
rs += `];\n`
writeFileSync(join(here, 'table.rs'), rs)

// Per-scalar behaviour beyond "removed or kept as is": the slug of every
// scalar whose slug is neither itself nor empty (lowercase mappings, space).
const mapped = []
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  const s = String.fromCodePoint(cp)
  const out = slug(s)
  if (out !== '' && out !== s) mapped.push([cp, out])
}
writeFileSync(join(here, 'fixtures/scalars.json'), JSON.stringify({ version: pkg.version, mapped }) + '\n')

