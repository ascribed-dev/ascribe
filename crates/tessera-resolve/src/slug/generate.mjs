const random = []
for (let i = 0; i < 400; i++) {
  const len = 1 + rnd(24)
  let s = ''
  for (let j = 0; j < len; j++) {
    const p = pools[rnd(pools.length)]
    s += p[rnd(p.length)]
  }
  random.push(s)
}
// A few random dense-scalar strings drawn from the whole of Unicode.
for (let i = 0; i < 200; i++) {
  let s = ''
  for (let j = 0; j < 12; j++) {
    let cp
    do cp = rnd(0x110000)
    while (cp >= 0xd800 && cp <= 0xdfff)
    s += String.fromCodePoint(cp)
  }
  random.push(s)
}

const cases = [...inputs, ...random].map((input) => ({ input, slug: slug(input) }))
const dupes = sequences.map((inputs) => {
  const s = new GithubSlugger()
  return { inputs, slugs: inputs.map((t) => s.slug(t)) }
})
writeFileSync(join(here, 'fixtures/slugs.json'), JSON.stringify({ version: pkg.version, cases, dupes }, null, 1) + '\n')
